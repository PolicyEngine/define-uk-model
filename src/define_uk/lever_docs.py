"""Generate docs/scenario-levers.md from ``scenarios.SCENARIO_LEVERS``.

    python -m define_uk.lever_docs          # rewrite the file
    python -m define_uk.lever_docs --check  # exit 1 if it is out of date

The table is built from committed data only, so it needs no cached run.
``tests/test_parameter_gate_hermetic.py`` fails if the committed file is not
what ``render()`` returns; ``tests/test_scenario_levers.py`` checks the data
itself against the cached run's parameter files where a cache exists.
"""

from __future__ import annotations

import sys
from pathlib import Path

from . import scenarios as sc

DOC = Path(__file__).resolve().parents[2] / "docs" / "scenario-levers.md"

# Lever -> the group it is listed under, in table order.
GROUPS = (
    ("Green public investment and its financing",
     ("GVT_INVEST", "GREEN_BONDS", "GREEN_POWER", "CO_NFF", "sh_rGVTNMFIG")),
    ("Power-sector regulation and subsidy",
     ("FF_BAN", "FF_CAP_BAN", "FF_INV_BAN", "TRANS_PASS", "TTRANS",
      "POWER_SUB")),
    ("Housing regulation and subsidy",
     ("HENBAN", "HIBAN", "HSELL", "THENBAN", "THIBAN", "TTRANSH",
      "HOUSING_SUB", "HOUSING_SUB_RATE")),
    ("Expectation switches", ("CRED", "GVT_CRED", "ELEC_BUFFER")),
)
ORDER = tuple(k for _, keys in GROUPS for k in keys)


def baseline_values() -> dict[str, str]:
    """The Baseline's printed value of every lever (one value each: the
    eight Baseline parameter rows are the same)."""
    out: dict[str, str] = {}
    for levers in sc.SCENARIO_LEVERS.values():
        for k, (base, _) in levers.items():
            if out.setdefault(k, base) != base:
                raise ValueError(f"{k}: two Baseline values recorded")
    return out


def _levers(name: str) -> str:
    levers = sc.SCENARIO_LEVERS[name]
    return ", ".join(f"{k} {levers[k][0]} → {levers[k][1]}"
                     for k in ORDER if k in levers)


def render() -> str:
    base = baseline_values()
    b = sc.BASELINE_POWER_SUBSIDY
    lines = [
        "# Scenario levers: what each scenario changes",
        "",
        "<!-- Generated by `python -m define_uk.lever_docs` from "
        "`define_uk.scenarios.SCENARIO_LEVERS`. Do not edit by hand: "
        "`tests/test_parameter_gate_hermetic.py` fails if this file and the "
        "data differ. -->",
        "",
        "Every served result is a scenario minus the Baseline of the same "
        "folder. This page lists, for each of the "
        f"{len(sc.SCENARIO_LEVERS)} registered scenarios, every parameter "
        "its cached parameter row sets away from that Baseline's, with both "
        "printed values. The source is the cached run's own "
        "`Parameters-sorted_*.csv` files; nothing comes from the upstream "
        "source code. `run_scenario` refuses a scenario whose cached row "
        "moves any other lever, moves one to another value, or leaves a "
        "listed one unmoved.",
        "",
        "One parameter is left out of every row because it is not a policy "
        "lever: `alpha_PPLR` is 0.2748 in every Baseline file and 0.2762 in "
        "every policy file (issue #20), so every delta also carries that "
        "change.",
        "",
        "## What the scenario names do not say",
        "",
        "- **The Baseline pays a power subsidy.** No switch in the "
        "Baseline's row is on (`POWER_SUB` = `GREEN_POWER` = 0), yet its "
        f"output file prints `{b['variable']}` > 0 from "
        f"{b['first_quarter']} ({b['first_quarter_value']} that quarter, "
        f"{b['last_quarter_value']} in 2040Q4, "
        f"{b['cumulative_2027_2040']} summed over 2027Q1–2040Q4; GBP bn "
        "per quarter). Every delta is measured against a Baseline that "
        "includes it.",
        "- **Green public investment replaces that subsidy.** In `GPI + "
        f"Green Bonds`, `SUBS_PS` is {b['gpi_subs_ps_cumulative']:g} "
        "throughout and the government spends "
        f"{b['gpi_spend_gvtps_cumulative']} on its own balance sheet "
        "(`SPEND_GVTPS`, same window). The net change in public power "
        "spending against the Baseline is "
        f"{b['gpi_spend_gvtps_cumulative'] - b['cumulative_2027_2040']:.2f}"
        " (91.2 in `define_uk.validation`, which sums the unrounded "
        "difference): the spending change the headline multiplier divides "
        "by.",
        "- **Green public investment is not one switch.** It sets "
        "`GVT_INVEST`, `GREEN_BONDS` and `GREEN_POWER`, and also `CO_NFF`, "
        "`sh_rGVTNMFIG`, `CRED` and `GVT_CRED`. The manual does not name "
        "the last four; what each does in the run is not established here.",
        "- **`CRED` and `GVT_CRED` move outside the power-sector block.** "
        "Every scenario of the government-investment and housing blocks "
        "sets them to 1 and 0. The Baseline holds the mutual-trust values "
        "(0.9 and 1). No fossil-fuel ban is on in those scenarios; "
        "whether the two switches have any effect without one is not "
        "established here.",
        "- **The combined policy is not the sum of its parts.** `Both "
        "Regulations + Subsidies` sets `FF_INV_BAN` = 165 and `TTRANS` = "
        "20, where the fossil-fuel ban on its own sets 161 and 16.",
        "- **The power subsidy has no regime.** `power_sector_subsidy` "
        "moves `POWER_SUB` alone under all five regime labels, so the five "
        "names are one solve (`docs/scenario-notes.md`).",
        "",
        "## Levers by scenario",
        "",
        "Baseline value → scenario value, as printed.",
        "",
        "| Scenario | Cached file | Levers changed |",
        "|---|---|---|",
    ]
    for name, _, folder, label, _ in sc._REGISTRY:
        lines.append(f"| `{name}` | `{folder}/{label}` | {_levers(name)} |")
    lines += [
        "",
        "## Scenarios by lever",
        "",
        "| Lever | Baseline | Set to |",
        "|---|---|---|",
    ]
    for group, keys in GROUPS:
        lines.append(f"| **{group}** | | |")
        for k in keys:
            by_value: dict[str, list[str]] = {}
            for name, levers in sc.SCENARIO_LEVERS.items():
                if k in levers:
                    by_value.setdefault(levers[k][1], []).append(name)
            sets = "; ".join(
                f"{value} in {len(names)} "
                + ("scenario" if len(names) == 1 else "scenarios")
                for value, names in by_value.items())
            lines.append(f"| `{k}` | {base[k]} | {sets} |")
    lines += [
        "",
        "## Keeping this page in sync",
        "",
        "```bash",
        "python -m define_uk.lever_docs          # regenerate",
        "python -m define_uk.lever_docs --check  # fail if out of date",
        "```",
        "",
        "`SCENARIO_LEVERS` is checked against the cached parameter files, "
        "and the Baseline subsidy figures against the cached output files, "
        "in `tests/test_scenario_levers.py` (needs the cached run, so it "
        "skips in CI).",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    text = render()
    if "--check" in argv:
        if not DOC.exists() or DOC.read_text() != text:
            print(f"{DOC} is out of date: run python -m define_uk.lever_docs")
            return 1
        return 0
    DOC.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
