"""DEFINE-UK 1.1 §5 parameters and initial values (clean-room transcription).

Transcribed from the *DEFINE-UK Model Manual, Version 1.1* (George &
Dafermos, April 2026):

- ``PARAMETERS``      — manual §5 Table 5, "Symbols and values for parameters
  and exogenous variables (baseline scenario)", pp. 53-62.
- ``INITIAL_VALUES``  — manual §5 Table 6, "Symbols and initial values for
  endogenous variables (baseline scenario)", pp. 63-79.

Both tables are transcribed completely. Values are exactly the manual's
printed figures (4 significant figures unless the manual prints fewer), so
identities hold only up to that rounding — see tests/test_accounting.py for
the rounding-aware tolerance.

Symbol normalization (manual symbol -> Python key):

- Subscripts become an underscore-separated suffix, with multi-part
  subscripts concatenated in the manual's order:
  ``CONS_HHP`` for CONS_{HHP}, ``GCF_PSFFR`` for GCF_{PSFFR},
  ``IBL_GVT_MFI`` for IBL_{GVT MFI} (GVT liabilities held by MFIs).
- Transfer flows keep the manual's ``TR`` marker attached to the
  instrument: ``IBATR_NFC``, ``EQLTR_PS``, ``RESTR_HH``, ``PENSTR``,
  ``INSTR_`` (trailing underscore avoids clashing with the insurance-stock
  transfer name and Python's builtin-ish look; INSTR_ is the manual's
  INS_{TR}).
- Model-determined twins of national-accounts variables put the manual's
  trailing ``M`` after the concept: ``LENDM_NFC`` for LEND_{NFCM},
  ``FNWM_GVT`` for FNW_{GVTM}.
- Greek letters are spelled out (``alpha0_CHHP``, ``beta_nfc``,
  ``eta_NFCT``, ``delta_KP``, ``omega_ELEC``, ``theta_P``); the bare Greek
  productivity/markup symbols become ``lam`` (lambda), ``mu``, ``nu``,
  ``epsilon`` (energy intensity of production).
- Rates of return keep the manual's lower-case ``r`` prefix:
  ``r_IBA_NFC``, ``r_IBL_GVT``, ``r_BOE``.

Known manual quirks (documented, not silently fixed):

- Table 6 cross-references equation numbers that do not match the equation
  numbering printed in the §3 body text (e.g. Table 6 says RP_NFC comes
  from "Eq. (101)" while the body prints it as Eq. (165)).  All
  ``manual_ref`` citations in this package use the §3 body numbering.
- SUBS_GVT / SUBS_PS (subsidy flows, §3.4.3 Eq. (281) and §3.4.2
  Eq. (136)) have no entry in Table 5 or Table 6; they are policy-scenario
  instruments and are zero in the baseline initial period. They are
  included here as 0.0 with a TODO marker.
- Table 6 documents LENDM ("overall model determined net lending — should
  equal 0 by definition") as 5.44 at the initial values: the manual's own
  tabulated LENDM_ROW (10.96) omits the DIVN_ROW term of §3.4.6
  Eq. (383). See tests/test_accounting.py.
"""

